export function bambuThreeMf(overrides: Partial<Record<string, string | null>> = {}): Uint8Array {
  const files: Record<string, string | Uint8Array | null> = {
    "[Content_Types].xml": CONTENT_TYPES,
    "3D/3dmodel.model": bambuModelXml(),
    "Metadata/slice_info.config": BAMBU_SLICE_INFO,
    "Metadata/model_settings.config": BAMBU_MODEL_SETTINGS,
    "Metadata/project_settings.config": BAMBU_PROJECT_SETTINGS,
    "Metadata/plate_1.png": FAKE_PNG,
    ...overrides,
  };
  const entries: BuilderEntry[] = Object.entries(files)
    .filter(([, v]) => v !== null)
    .map(([name, data]) => ({ name, data: data as string | Uint8Array }));
  return buildZip(entries);
}

/** 3MF só com geometria (sem nenhum dado de fatiamento). */
export function geometryOnlyThreeMf(): Uint8Array {
  return buildZip([
    { name: "[Content_Types].xml", data: CONTENT_TYPES },
    { name: "3D/3dmodel.model", data: `<?xml version="1.0"?><model unit="millimeter"><metadata name="Title">Cubo</metadata><resources/><build/></model>` },
  ]);
}

